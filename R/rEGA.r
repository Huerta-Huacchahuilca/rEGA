#' @title Reliability Exploratory Graph Analysis (rEGA)
#'
#' @description
#' Estimates Reliability Exploratory Graph Analysis (\code{rEGA}) by decomposing the
#' support-refitted Markov precision matrix via the Neumann-Markov resolvent operator.
#' Partitions each item's standardized unit variance into Within-Community Network
#' Communality (\eqn{h_i^2}{h_i^2}), Bridging Variance (\eqn{\beta_i^2}{beta_i^2}),
#' and Markov Nodal Uniqueness (\eqn{\psi_i^2}{psi_i^2}), satisfying the exact
#' conservation law \eqn{h_i^2 + \beta_i^2 + \psi_i^2 = 1}{h_i^2 + beta_i^2 + psi_i^2 = 1}.
#' Computes closed-form structural reliability coefficients (Coefficient Gamma:
#' \eqn{\Gamma_c}{Gamma_c} per dimension and \eqn{\Gamma_t}{Gamma_t} total),
#' Global Graph Noise (\eqn{\Psi_G}{Psi_G}), and Graph Standard Error of Measurement
#' (\eqn{SEM_c}{SEM_c}).
#'
#' Dual-Pathway Architecture:
#' \itemize{
#'   \item \strong{Pathway A (Pre-estimated EGA model)}: Pass an existing \code{EGAnet} object
#'         to \code{ega.obj}. \code{rEGA} extracts the correlation matrix, regularized network,
#'         and communities, performs support-constrained MLE refitting, and computes all
#'         variance and reliability decompositions.
#'   \item \strong{Pathway B (Standalone mode)}: Pass raw item data or a correlation matrix to
#'         \code{data} with \code{ega.obj = NULL}. \code{rEGA} autonomously performs correlation
#'         estimation, Golino et al. (2020) unidimensionality checking, iterative \code{EBICglasso}
#'         estimation, support refitting, purity-weighted community detection, and reliability analysis.
#' }
#'
#' @param data A numeric \code{data.frame} or \code{matrix} of raw item responses
#'   (\eqn{n \times p}{n x p}) or a symmetric correlation matrix (\eqn{p \times p}{p x p}).
#'   Optional if \code{ega.obj} contains raw data or correlations.
#' @param n Integer. Sample size if \code{data} is a correlation matrix.
#' @param ega.obj Optional object of class \code{"EGA"} generated by \code{EGAnet::EGA()}.
#'   If \code{NULL} (default), \code{rEGA} estimates the network autonomously.
#' @param use.ega.communities Logical. If \code{ega.obj} is supplied, should \code{rEGA} retain
#'   the community partition from \code{ega.obj} (\code{TRUE}) or re-estimate communities on the
#'   purity-weighted adjacency matrix \eqn{A^{rEGA}}{A^rEGA} (\code{FALSE})? Default is \code{FALSE}.
#' @param cor.method Character. Correlation method in standalone mode:
#'   \code{"cor_auto"} (default), \code{"polychoric"}, \code{"pearson"}, or \code{"spearman"}.
#' @param uni.method Character. Unidimensionality adjustment method following Golino et al. (2020):
#'   \code{"expand"} (default, simulates 4 reference variables loading .70 on a single factor)
#'   or \code{"none"}.
#' @param gamma Numeric. Initial \code{EBICglasso} hyperparameter \eqn{\gamma}{gamma}.
#'   Default is \code{0.50} (automatically steps down to \code{0.25} and \code{0.00} if disconnected
#'   nodes occur).
#' @param lambda.min.ratio Numeric. Ratio of minimum to maximum regularization parameter
#'   (\eqn{\lambda_{min} / \lambda_{max}}{lambda_min / lambda_max}). Default is \code{0.10}.
#' @param nlambda Integer. Number of candidate \eqn{\lambda}{lambda} values in the \code{EBICglasso}
#'   grid. Default is \code{100}.
#' @param algorithm Character. Community detection algorithm: \code{"walktrap"} (default),
#'   \code{"leiden"}, or \code{"louvain"}.
#' @param walktrap.steps Integer. Number of random walk steps if \code{algorithm = "walktrap"}.
#'   Default is \code{4}.
#' @param leiden.objective Character. Objective function if \code{algorithm = "leiden"}:
#'   \code{"modularity"} (default) or \code{"CPM"}.
#' @param resolution.parameter Numeric. Resolution parameter if \code{algorithm = "leiden"}.
#'   Default is \code{1.0}.
#' @param weights.type Character. Weighting scheme for composite score reliability \eqn{\Gamma_c}{Gamma_c}:
#'   \code{"unit"} (default, unit weights \eqn{w_i = 1}{w_i = 1}) or \code{"purity"}
#'   (\eqn{w_i = \sqrt{h_{G,i}^2}}{w_i = sqrt(h_{G,i}^2)}).
#' @param refit.tol Numeric. Convergence tolerance for support-constrained MLE refitting.
#'   Default is \code{1e-6}.
#' @param plot.rEGA Logical. Should the diagnostic variance decomposition plot be displayed?
#'   Default is \code{TRUE}.
#' @param seed Integer. Random seed for reproducibility in unidimensionality simulation and Leiden
#'   partitioning. Default is \code{2026}.
#'
#' @return An object of class \code{"rEGA"} containing:
#' \itemize{
#'   \item \code{network.refit}: Unbiased partial correlation matrix \eqn{\hat{\Omega}}{Omega_hat} after support refitting.
#'   \item \code{network.glasso}: Initial regularized network \eqn{\hat{\Omega}_\lambda}{Omega_lambda}.
#'   \item \code{adjacency.rEGA}: Purity-weighted adjacency matrix \eqn{A_{ij}^{rEGA}}{A_ij^rEGA}.
#'   \item \code{K.refit}: Unbiased refitted precision matrix \eqn{\hat{K}_{refit}}{K_refit}.
#'   \item \code{D.K}: Diagonal matrix of conditional nodal precisions \eqn{\hat{D}_K}{D_K}.
#'   \item \code{resolvent}: Global Markov resolvent matrix \eqn{Q = (I - \hat{\Omega})^{-1}}{Q = (I - Omega_hat)^(-1)}.
#'   \item \code{R.obs}: Observed positive-definite correlation matrix.
#'   \item \code{wc}: Named integer vector of community memberships.
#'   \item \code{n.dim}: Number of estimated dimensions.
#'   \item \code{nodal.triad}: Data frame of item-level parameters (\eqn{h_i^2}{h_i^2}, \eqn{\beta_i^2}{beta_i^2},
#'         \eqn{\psi_i^2}{psi_i^2}, \eqn{h_{G,i}^2}{h_{G,i}^2}, \eqn{\hat{k}_{ii}}{k_ii}, and conservation sum).
#'   \item \code{net.loadings}: Matrix of standardized network loadings across communities.
#'   \item \code{reliability}: List containing dimension-level summary table (\code{$dimensions}:
#'         \eqn{\Gamma_c}{Gamma_c}, \eqn{SEM_c^{std}}{SEM_c^std}, \eqn{SEM_c^{raw}}{SEM_c^raw})
#'         and global metrics (\code{$Gamma.t}, \code{$Psi.G}, \code{$SEM.total.std}, \code{$SEM.total.raw}).
#'   \item \code{audit.metadata}: List of algebraic verification checks, active edge counts,
#'         \eqn{\lambda}{lambda}, \eqn{\gamma}{gamma}, and SHA-256 data hash.
#' }
#'
#' @importFrom stats cor cov2cor sd median quantile rnorm complete.cases
#' @importFrom utils globalVariables packageVersion sessionInfo
#' @importFrom Matrix nearPD
#' @importFrom MASS mvrnorm
#' @importFrom glasso glasso
#' @importFrom qgraph EBICglasso cor_auto
#' @importFrom igraph graph_from_adjacency_matrix cluster_walktrap cluster_leiden cluster_louvain membership E
#' @importFrom psych polychoric cor.smooth
#' @export
#'
#' @examples
#' set.seed(123)
#' Sigma <- matrix(0.25, 6, 6)
#' Sigma[1:3, 1:3] <- 0.65
#' Sigma[4:6, 4:6] <- 0.65
#' diag(Sigma) <- 1
#' dat <- as.data.frame(MASS::mvrnorm(n = 300, mu = rep(0, 6), Sigma = Sigma))
#' colnames(dat) <- paste0("Item", 1:6)
#' fit <- rEGA(data = dat, cor.method = "pearson", plot.rEGA = FALSE)
#' print(fit)
rEGA <- function(data = NULL,
                 n = NULL,
                 ega.obj = NULL,
                 use.ega.communities = FALSE,
                 cor.method = c("cor_auto", "polychoric", "pearson", "spearman"),
                 uni.method = c("expand", "none"),
                 gamma = 0.50,
                 lambda.min.ratio = 0.10,
                 nlambda = 100L,
                 algorithm = c("walktrap", "leiden", "louvain"),
                 walktrap.steps = 4L,
                 leiden.objective = c("modularity", "CPM"),
                 resolution.parameter = 1.0,
                 weights.type = c("unit", "purity"),
                 refit.tol = 1e-6,
                 plot.rEGA = TRUE,
                 seed = 2026L) {

  cor.method <- match.arg(cor.method)
  uni.method <- match.arg(uni.method)
  algorithm <- match.arg(algorithm)
  leiden.objective <- match.arg(leiden.objective)
  weights.type <- match.arg(weights.type)

  t0 <- Sys.time()
  raw_data <- NULL
  item_sds <- NULL
  R_obs <- NULL
  Omega_glasso <- NULL
  ega_wc <- NULL
  gamma_used <- gamma
  pathway_used <- "Standalone"

  # ---------------------------------------------------------------------------
  # STAGE 1: DUAL-PATHWAY INPUT EXTRACTION (EGAnet OBJECT OR STANDALONE DATA)
  # ---------------------------------------------------------------------------
  if (!is.null(ega.obj)) {
    pathway_used <- "EGAnet_Bridge"

    if (!is.null(ega.obj$correlation)) {
      R_obs <- as.matrix(ega.obj$correlation)
    } else if (!is.null(ega.obj$cor.data)) {
      R_obs <- as.matrix(ega.obj$cor.data)
    }

    if (!is.null(ega.obj$network)) {
      Omega_glasso <- as.matrix(ega.obj$network)
    }

    if (!is.null(ega.obj$wc)) {
      ega_wc <- as.integer(ega.obj$wc)
    }

    if (is.null(n) && !is.null(ega.obj$n)) {
      n <- as.integer(ega.obj$n)
    }

    if (!is.null(data)) {
      if (nrow(data) != ncol(data) || !isSymmetric(as.matrix(data))) {
        raw_data <- as.data.frame(data)
        raw_data <- raw_data[stats::complete.cases(raw_data), , drop = FALSE]
        n <- nrow(raw_data)
        item_sds <- apply(raw_data, 2, stats::sd, na.rm = TRUE)
        if (is.null(R_obs)) {
          R_obs <- .compute_rEGA_cor(raw_data, cor.method = cor.method)
        }
      } else {
        R_obs <- as.matrix(data)
      }
    }

    if (is.null(R_obs)) {
      stop("Could not extract the correlation matrix from 'ega.obj'. Please supply 'data'.")
    }
    if (is.null(n)) {
      stop("Sample size 'n' was not found in 'ega.obj'. Please specify 'n' or provide raw 'data'.")
    }
  } else {
    if (is.null(data)) {
      stop("Please provide either 'data' (raw data or correlation matrix) or a pre-estimated 'ega.obj'.")
    }
    mat_input <- as.matrix(data)
    if (nrow(mat_input) == ncol(mat_input) && isSymmetric(mat_input, tol = 1e-5) &&
        all(abs(diag(mat_input) - 1) < 1e-4)) {
      R_obs <- mat_input
      if (is.null(n)) {
        stop("When 'data' is a correlation matrix, sample size 'n' must be specified.")
      }
      item_sds <- rep(1.0, ncol(R_obs))
    } else {
      raw_data <- as.data.frame(data)
      raw_data <- raw_data[stats::complete.cases(raw_data), , drop = FALSE]
      n <- nrow(raw_data)
      if (n < 10) {
        stop("Sample size 'n' is too small after removing missing values.")
      }
      item_sds <- apply(raw_data, 2, stats::sd, na.rm = TRUE)
      R_obs <- .compute_rEGA_cor(raw_data, cor.method = cor.method)
    }
  }

  p <- ncol(R_obs)
  item_names <- colnames(R_obs)
  if (is.null(item_names)) {
    item_names <- paste0("V", seq_len(p))
  }
  dimnames(R_obs) <- list(item_names, item_names)
  if (is.null(item_sds)) {
    item_sds <- rep(1.0, p)
  }
  names(item_sds) <- item_names

  # Ensure positive definiteness of R_obs
  R_obs <- .ensure_pd_cor(R_obs)

  # ---------------------------------------------------------------------------
  # STAGE 2: UNIDIMENSIONALITY CHECK (GOLINO ET AL., 2020 EXPANSION) & GLASSO
  # ---------------------------------------------------------------------------
  is_unidimensional_override <- FALSE
  if (is.null(Omega_glasso)) {
    if (uni.method == "expand") {
      is_unidimensional_override <- .check_unidimensional_golino(
        raw_data = raw_data, R_obs = R_obs, n = n,
        cor.method = cor.method, gamma = gamma,
        lambda.min.ratio = lambda.min.ratio, nlambda = nlambda,
        algorithm = algorithm, walktrap.steps = walktrap.steps,
        leiden.objective = leiden.objective,
        resolution.parameter = resolution.parameter,
        seed = seed
      )
    }

    ebic_res <- .estimate_ebic_glasso_iterative(
      R_obs = R_obs, n = n, gamma = gamma,
      lambda.min.ratio = lambda.min.ratio, nlambda = nlambda
    )
    Omega_glasso <- ebic_res$Omega_glasso
    gamma_used <- ebic_res$gamma_used
  }

  dimnames(Omega_glasso) <- list(item_names, item_names)

  # ---------------------------------------------------------------------------
  # STAGE 3: SUPPORT EXTRACTION & CONSTRAINED MLE REFITTING (K_refit)
  # ---------------------------------------------------------------------------
  refit_obj <- .refit_precision_support(
    R_obs = R_obs,
    Omega_glasso = Omega_glasso,
    tol = refit.tol
  )
  K_refit <- refit_obj$K_refit
  Omega_refit <- refit_obj$Omega_refit
  D_K <- refit_obj$D_K
  active_edges <- refit_obj$active_edges

  # ---------------------------------------------------------------------------
  # STAGE 4: NEUMANN-MARKOV RESOLVENT OPERATOR & GLOBAL NODAL PURITY
  # ---------------------------------------------------------------------------
  I_p <- diag(1, p)
  dimnames(I_p) <- list(item_names, item_names)

  Q_res <- tryCatch(
    solve(I_p - Omega_refit),
    error = function(e) {
      Matrix:: nearPD(I_p - Omega_refit, corr = FALSE)$mat |> solve() |> as.matrix()
    }
  )
  dimnames(Q_res) <- list(item_names, item_names)

  q_diag <- pmax(diag(Q_res), 1.0)
  psi2_i <- 1.0 / q_diag
  h2_G_i <- pmax(0.0, 1.0 - psi2_i)

  # ---------------------------------------------------------------------------
  # STAGE 5: PURITY-WEIGHTED ADJACENCY MATRIX & COMMUNITY DETECTION
  # ---------------------------------------------------------------------------
  purity_outer <- sqrt(outer(h2_G_i, h2_G_i, "*"))
  A_rEGA <- abs(Omega_refit) * purity_outer
  diag(A_rEGA) <- 0.0
  A_rEGA <- (A_rEGA + t(A_rEGA)) / 2.0
  dimnames(A_rEGA) <- list(item_names, item_names)

  if (!is.null(ega_wc) && isTRUE(use.ega.communities) && length(ega_wc) == p) {
    wc <- as.integer(factor(ega_wc))
  } else if (isTRUE(is_unidimensional_override)) {
    wc <- rep(1L, p)
  } else {
    wc <- .detect_communities_rEGA(
      A_mat = A_rEGA,
      algorithm = algorithm,
      walktrap.steps = walktrap.steps,
      leiden.objective = leiden.objective,
      resolution.parameter = resolution.parameter,
      seed = seed
    )
  }
  names(wc) <- item_names
  n_dim <- length(unique(wc[!is.na(wc)]))

  # ---------------------------------------------------------------------------
  # STAGE 6: NODAL VARIANCE CONSERVATION TRIAD (h_i^2 + beta_i^2 + psi_i^2 = 1)
  # ---------------------------------------------------------------------------
  h2_i <- numeric(p)
  beta2_i <- numeric(p)
  names(h2_i) <- item_names
  names(beta2_i) <- item_names

  unique_comms <- sort(unique(wc))
  for (c_id in unique_comms) {
    idx_c <- which(wc == c_id)
    if (length(idx_c) == 1L) {
      q_intra_c <- 1.0
    } else {
      I_c <- diag(1, length(idx_c))
      Omega_cc <- Omega_refit[idx_c, idx_c, drop = FALSE]
      Q_cc <- tryCatch(
        solve(I_c - Omega_cc),
        error = function(e) diag(1, length(idx_c))
      )
      q_intra_c <- pmax(diag(Q_cc), 1.0)
    }
    inv_q_intra <- 1.0 / q_intra_c
    h2_i[idx_c] <- pmax(0.0, 1.0 - inv_q_intra)
    beta2_i[idx_c] <- pmax(0.0, inv_q_intra - psi2_i[idx_c])
  }

  # Exact algebraic normalization check
  triad_sum <- h2_i + beta2_i + psi2_i
  k_diag <- diag(K_refit)

  nodal_triad <- data.frame(
    Item = item_names,
    Community = wc,
    h2 = round(h2_i, 6),
    beta2 = round(beta2_i, 6),
    psi2 = round(psi2_i, 6),
    h2_G = round(h2_G_i, 6),
    K_ii = round(k_diag, 6),
    Conservation_Sum = round(triad_sum, 6),
    stringsAsFactors = FALSE
  )
  rownames(nodal_triad) <- NULL

  # ---------------------------------------------------------------------------
  # STAGE 7: STANDARDIZED NETWORK LOADINGS (CHRISTENSEN & GOLINO, 2020)
  # ---------------------------------------------------------------------------
  net_loadings <- .compute_network_loadings(Omega_refit, wc, item_names)

  # ---------------------------------------------------------------------------
  # STAGE 8: STRUCTURAL RELIABILITY (GAMMA_c, GAMMA_t, PSI_G, AND GRAPH SEM)
  # ---------------------------------------------------------------------------
  Sigma_reprod <- tryCatch(solve(K_refit), error = function(e) R_obs)
  dimnames(Sigma_reprod) <- list(item_names, item_names)
  D_K_inv <- diag(1.0 / k_diag, p, p)
  D_K_inv_sqrt <- diag(1.0 / sqrt(k_diag), p, p)
  dimnames(D_K_inv) <- list(item_names, item_names)
  dimnames(D_K_inv_sqrt) <- list(item_names, item_names)

  Psi_G <- sum(diag(D_K_inv)) / sum(diag(Sigma_reprod))

  if (weights.type == "purity") {
    w_vec <- sqrt(pmax(h2_G_i, 1e-6))
  } else {
    w_vec <- rep(1.0, p)
  }
  names(w_vec) <- item_names

  # Total Network Gamma (Gamma_t)
  num_total <- as.numeric(t(w_vec) %*% D_K_inv %*% w_vec)
  den_total <- as.numeric(t(w_vec) %*% Sigma_reprod %*% w_vec)
  Gamma_t <- pmax(0.0, pmin(1.0, 1.0 - (num_total / den_total)))
  SEM_total_std <- sqrt(num_total)

  if (!is.null(raw_data)) {
    total_raw_sd <- stats::sd(as.matrix(raw_data) %*% w_vec, na.rm = TRUE)
  } else {
    D_sd <- diag(item_sds, p, p)
    cov_raw <- D_sd %*% R_obs %*% D_sd
    total_raw_sd <- sqrt(as.numeric(t(w_vec) %*% cov_raw %*% w_vec))
  }
  SEM_total_raw <- total_raw_sd * sqrt(1.0 - Gamma_t)

  # Dimensional Network Gamma (Gamma_c) and SEM_c
  dim_rows <- lapply(unique_comms, function(c_id) {
    idx_c <- which(wc == c_id)
    p_c <- length(idx_c)
    w_c <- w_vec[idx_c]
    k_c <- k_diag[idx_c]

    if (p_c == 1L) {
      Gamma_c <- h2_G_i[idx_c]
      SEM_c_std <- sqrt(1.0 / k_c)
    } else {
      I_c <- diag(1, p_c)
      Omega_cc <- Omega_refit[idx_c, idx_c, drop = FALSE]
      Q_cc <- tryCatch(solve(I_c - Omega_cc), error = function(e) I_c)
      D_Kc_inv <- diag(1.0 / k_c, p_c, p_c)
      D_Kc_inv_sqrt <- diag(1.0 / sqrt(k_c), p_c, p_c)
      Sigma_cc_intra <- D_Kc_inv_sqrt %*% Q_cc %*% D_Kc_inv_sqrt

      err_var_c <- as.numeric(t(w_c) %*% D_Kc_inv %*% w_c)
      tot_var_c <- as.numeric(t(w_c) %*% Sigma_cc_intra %*% w_c)
      Gamma_c <- pmax(0.0, pmin(1.0, 1.0 - (err_var_c / tot_var_c)))
      SEM_c_std <- sqrt(err_var_c)
    }

    if (!is.null(raw_data)) {
      sd_raw_c <- stats::sd(as.matrix(raw_data[, idx_c, drop = FALSE]) %*% w_c, na.rm = TRUE)
    } else {
      D_sd_c <- diag(item_sds[idx_c], p_c, p_c)
      cov_raw_c <- D_sd_c %*% R_obs[idx_c, idx_c, drop = FALSE] %*% D_sd_c
      sd_raw_c <- sqrt(as.numeric(t(w_c) %*% cov_raw_c %*% w_c))
    }
    SEM_c_raw <- sd_raw_c * sqrt(1.0 - Gamma_c)

    data.frame(
      Dimension = c_id,
      n_Items = p_c,
      Gamma_c = round(Gamma_c, 6),
      Mean_h2 = round(mean(h2_i[idx_c]), 6),
      Mean_beta2 = round(mean(beta2_i[idx_c]), 6),
      Mean_psi2 = round(mean(psi2_i[idx_c]), 6),
      SEM_std = round(SEM_c_std, 6),
      SD_Raw = round(sd_raw_c, 6),
      SEM_raw = round(SEM_c_raw, 6),
      stringsAsFactors = FALSE
    )
  })
  dim_reliability_df <- do.call(rbind, dim_rows)

  # Exact resolvent 3-level decomposition check
  Level0_Error <- D_K_inv
  Level1_Direct <- D_K_inv_sqrt %*% Omega_refit %*% D_K_inv_sqrt
  Level2_Reverb <- D_K_inv_sqrt %*% (Omega_refit %*% Q_res %*% Omega_refit) %*% D_K_inv_sqrt
  dimnames(Level1_Direct) <- list(item_names, item_names)
  dimnames(Level2_Reverb) <- list(item_names, item_names)
  alg_max_err <- max(abs(Sigma_reprod - (Level0_Error + Level1_Direct + Level2_Reverb)))

  out <- list(
    network.refit = Omega_refit,
    network.glasso = Omega_glasso,
    adjacency.rEGA = A_rEGA,
    K.refit = K_refit,
    D.K = D_K,
    resolvent = Q_res,
    R.obs = R_obs,
    Sigma.reprod = Sigma_reprod,
    resolvent.levels = list(
      Level0_Conditional_Error = Level0_Error,
      Level1_Direct_Coupling = Level1_Direct,
      Level2_Systemic_Reverberation = Level2_Reverb
    ),
    wc = wc,
    n.dim = n_dim,
    nodal.triad = nodal_triad,
    net.loadings = net_loadings,
    reliability = list(
      dimensions = dim_reliability_df,
      Gamma.t = Gamma_t,
      Psi.G = Psi_G,
      SEM.total.std = SEM_total_std,
      SEM.total.raw = SEM_total_raw
    ),
    audit.metadata = list(
      pathway = pathway_used,
      n = n,
      p = p,
      cor.method = cor.method,
      algorithm = algorithm,
      gamma.used = gamma_used,
      active.edges = active_edges,
      min.eigen.Krefit = min(eigen(K_refit, symmetric = TRUE, only.values = TRUE)$values),
      max.algebraic.error = alg_max_err,
      max.conservation.error = max(abs(triad_sum - 1.0)),
      data.sha256 = digest::digest(if (!is.null(raw_data)) raw_data else R_obs, algo = "sha256"),
      runtime.sec = as.numeric(difftime(Sys.time(), t0, units = "secs"))
    ),
    raw.data = raw_data,
    call = match.call()
  )

  class(out) <- "rEGA"

  if (isTRUE(plot.rEGA)) {
    print(plot(out))
  }

  return(out)
}

# =============================================================================
# INTERNAL HELPER FUNCTIONS
# =============================================================================

.compute_rEGA_cor <- function(df, cor.method = "cor_auto") {
  if (cor.method == "cor_auto") {
    R <- suppressMessages( suppressWarnings(qgraph::cor_auto(df)) )
  } else if (cor.method == "polychoric") {
    R <- tryCatch(
      suppressWarnings(psych::polychoric(df, smooth = TRUE, correct = 0.01)$rho),
      error = function(e) stats::cor(df, use = "pairwise.complete.obs")
    )
  } else if (cor.method == "spearman") {
    R <- stats::cor(df, use = "pairwise.complete.obs", method = "spearman")
  } else {
    R <- stats::cor(df, use = "pairwise.complete.obs", method = "pearson")
  }
  return(as.matrix(R))
}

.ensure_pd_cor <- function(R) {
  R <- (R + t(R)) / 2.0
  diag(R) <- 1.0
  ev <- eigen(R, symmetric = TRUE, only.values = TRUE)$values
  if (min(ev) < 1e-5) {
    R <- as.matrix(Matrix::nearPD(R, corr = TRUE, keepDiag = TRUE)$mat)
  }
  return(R)
}

.estimate_ebic_glasso_iterative <- function(R_obs, n, gamma = 0.50,
                                            lambda.min.ratio = 0.10, nlambda = 100L) {
  candidate_gammas <- sort(unique(c(gamma, 0.25, 0.00)), decreasing = TRUE)
  candidate_gammas <- candidate_gammas[candidate_gammas <= gamma]

  Omega_out <- NULL
  g_selected <- gamma

  for (g_val in candidate_gammas) {
    net_try <- suppressMessages(suppressWarnings(
      qgraph::EBICglasso(
        S = R_obs,
        n = n,
        gamma = g_val,
        lambda.min.ratio = lambda.min.ratio,
        nlambda = nlambda,
        returnAllResults = FALSE,
        checkPD = FALSE
      )
    ))
    net_try <- as.matrix(net_try)
    deg <- rowSums(abs(net_try) > 1e-7)
    Omega_out <- net_try
    g_selected <- g_val
    if (all(deg > 0)) {
      break
    }
  }
  return(list(Omega_glasso = Omega_out, gamma_used = g_selected))
}

.refit_precision_support <- function(R_obs, Omega_glasso, tol = 1e-6) {
  p <- ncol(R_obs)
  item_names <- colnames(R_obs)
  E_active <- (abs(Omega_glasso) > 1e-6)
  diag(E_active) <- FALSE
  active_edges <- sum(E_active[upper.tri(E_active)])

  if (active_edges == 0L) {
    K_refit <- diag(1, p)
  } else {
    zero_mat <- which(!E_active & row(E_active) != col(E_active), arr.ind = TRUE)
    if (nrow(zero_mat) == 0L) {
      K_refit <- tryCatch(
        solve(R_obs),
        error = function(e) glasso::glasso(s = R_obs, rho = 1e-4, penalize.diagonal = FALSE)$wi
      )
    } else {
      gl_refit <- suppressWarnings(
        glasso::glasso(
          s = R_obs,
          rho = 1e-8,
          zero = zero_mat,
          penalize.diagonal = FALSE,
          thr = tol
        )
      )
      K_refit <- as.matrix(gl_refit$wi)
    }
  }

  K_refit <- (K_refit + t(K_refit)) / 2.0
  ev_k <- eigen(K_refit, symmetric = TRUE, only.values = TRUE)$values
  if (min(ev_k) <= 1e-6) {
    K_refit <- as.matrix(Matrix::nearPD(K_refit, corr = FALSE)$mat)
  }
  dimnames(K_refit) <- list(item_names, item_names)

  k_diag <- pmax(diag(K_refit), 1e-6)
  D_K <- diag(k_diag, p, p)
  dimnames(D_K) <- list(item_names, item_names)

  D_K_inv_sqrt <- diag(1.0 / sqrt(k_diag), p, p)
  Omega_refit <- -D_K_inv_sqrt %*% K_refit %*% D_K_inv_sqrt
  diag(Omega_refit) <- 0.0
  Omega_refit[!E_active] <- 0.0
  Omega_refit <- (Omega_refit + t(Omega_refit)) / 2.0
  dimnames(Omega_refit) <- list(item_names, item_names)

  return(list(
    K_refit = K_refit,
    Omega_refit = Omega_refit,
    D_K = D_K,
    active_edges = active_edges
  ))
}

.detect_communities_rEGA <- function(A_mat, algorithm = "walktrap",
                                     walktrap.steps = 4L,
                                     leiden.objective = "modularity",
                                     resolution.parameter = 1.0,
                                     seed = 2026L) {
  p <- ncol(A_mat)
  if (sum(A_mat) <= 1e-8) {
    return(seq_len(p))
  }

  g <- igraph::graph_from_adjacency_matrix(A_mat, mode = "max", weighted = TRUE, diag = FALSE)

  if (!is.null(seed)) {
    set.seed(seed)
  }

  if (algorithm == "leiden") {
    leiden_args <- list(
      graph = g,
      objective_function = leiden.objective,
      weights = igraph::E(g)$weight
    )
    if ("resolution" %in% names(formals(igraph::cluster_leiden))) {
      leiden_args$resolution <- resolution.parameter
    } else {
      leiden_args$resolution_parameter <- resolution.parameter
    }
    comm_obj <- do.call(igraph::cluster_leiden, leiden_args)
  } else if (algorithm == "louvain") {
    comm_obj <- igraph::cluster_louvain(g, weights = igraph::E(g)$weight)
  } else {
    comm_obj <- igraph::cluster_walktrap(g, weights = igraph::E(g)$weight, steps = walktrap.steps)
  }

  wc <- as.integer(igraph::membership(comm_obj))
  return(wc)
}

.check_unidimensional_golino <- function(raw_data, R_obs, n, cor.method, gamma,
                                         lambda.min.ratio, nlambda, algorithm,
                                         walktrap.steps, leiden.objective,
                                         resolution.parameter, seed) {
  set.seed(seed)
  p <- ncol(R_obs)
  p_sim <- 4L
  load_sim <- 0.70
  Sigma_sim <- matrix(load_sim^2, p_sim, p_sim)
  diag(Sigma_sim) <- 1.0

  if (!is.null(raw_data)) {
    sim_dat <- MASS::mvrnorm(n = nrow(raw_data), mu = rep(0, p_sim), Sigma = Sigma_sim)
    colnames(sim_dat) <- paste0("SIM_UNI_", seq_len(p_sim))
    combined_dat <- cbind(sim_dat, raw_data)
    R_exp <- .compute_rEGA_cor(combined_dat, cor.method = cor.method)
  } else {
    R_exp <- matrix(0, p + p_sim, p + p_sim)
    R_exp[seq_len(p_sim), seq_len(p_sim)] <- Sigma_sim
    R_exp[(p_sim + 1):(p + p_sim), (p_sim + 1):(p + p_sim)] <- R_obs
    colnames(R_exp) <- rownames(R_exp) <- c(paste0("SIM_UNI_", seq_len(p_sim)), colnames(R_obs))
  }
  R_exp <- .ensure_pd_cor(R_exp)

  ebic_exp <- .estimate_ebic_glasso_iterative(R_exp, n = n, gamma = gamma,
                                              lambda.min.ratio = lambda.min.ratio,
                                              nlambda = nlambda)
  wc_exp <- .detect_communities_rEGA(
    A_mat = abs(ebic_exp$Omega_glasso),
    algorithm = algorithm,
    walktrap.steps = walktrap.steps,
    leiden.objective = leiden.objective,
    resolution.parameter = resolution.parameter,
    seed = seed
  )
  n_dim_exp <- length(unique(wc_exp))
  return(n_dim_exp <= 2L)
}

.compute_network_loadings <- function(Omega_refit, wc, item_names) {
  unique_comms <- sort(unique(wc))
  K_dim <- length(unique_comms)
  p <- ncol(Omega_refit)
  A_abs <- abs(Omega_refit)
  diag(A_abs) <- 0.0

  load_mat <- matrix(0.0, nrow = p, ncol = K_dim)
  rownames(load_mat) <- item_names
  colnames(load_mat) <- paste0("Dim_", unique_comms)

  for (idx_k in seq_along(unique_comms)) {
    c_id <- unique_comms[idx_k]
    nodes_c <- which(wc == c_id)
    load_mat[, idx_k] <- rowSums(A_abs[, nodes_c, drop = FALSE])
  }

  col_totals <- sqrt(colSums(load_mat))
  for (idx_k in seq_len(K_dim)) {
    if (col_totals[idx_k] > 1e-8) {
      load_mat[, idx_k] <- load_mat[, idx_k] / col_totals[idx_k]
    }
  }
  return(round(load_mat, 4))
}
